/**
 * DEC Special Graphics (`ESC ( 0`) → CP437 glyph index.
 *
 * This mapping is *why* CP437 was the right glyph ROM for the fiction: DEC's
 * line-drawing set lands on box glyphs the font already has, so `vi`, `htop`
 * and ncurses draw their frames correctly for free.
 *
 * The ROM does not contain every DEC glyph. Three groups fall short, and each
 * resolves to the nearest honest substitute rather than to a wrong symbol:
 *
 * - **Control pictures** (`b`–`e`, `h`, `i` — HT, FF, CR, LF, NL, VT) render as
 *   blanks. CP437 has no mnemonic glyphs for them.
 * - **Scan lines** (`o`, `p`, `r` — 1, 3 and 7) collapse onto the single
 *   horizontal rule the ROM does have, `─`. Scan line 9 (`s`) maps to `_`,
 *   which sits on the cell's bottom row and so is an exact positional match.
 * - **`≠`** (`|`) renders as a blank; CP437 has no not-equal sign, and a blank
 *   is less misleading than the `≡` it would otherwise be forced onto.
 *
 * Anything outside `0x5F`–`0x7E` is not part of the set and is not mapped —
 * callers pass such bytes through to `CHARACTERS` unchanged.
 */
export const DEC_SPECIAL_GRAPHICS: Record<number, number> = {
  0x5f: 0x20, // _  blank
  0x60: 0x04, // `  ◆  diamond
  0x61: 0xb1, // a  ▒  checkerboard
  0x62: 0x20, // b  ␉  HT          — no glyph in ROM
  0x63: 0x20, // c  ␌  FF          — no glyph in ROM
  0x64: 0x20, // d  ␍  CR          — no glyph in ROM
  0x65: 0x20, // e  ␊  LF          — no glyph in ROM
  0x66: 0xf8, // f  °  degree
  0x67: 0xf1, // g  ±  plus/minus
  0x68: 0x20, // h  ␤  NL          — no glyph in ROM
  0x69: 0x20, // i  ␋  VT          — no glyph in ROM
  0x6a: 0xd9, // j  ┘  lower right corner
  0x6b: 0xbf, // k  ┐  upper right corner
  0x6c: 0xda, // l  ┌  upper left corner
  0x6d: 0xc0, // m  └  lower left corner
  0x6e: 0xc5, // n  ┼  crossing lines
  0x6f: 0xc4, // o  ⎺  scan line 1 — collapsed onto ─
  0x70: 0xc4, // p  ⎻  scan line 3 — collapsed onto ─
  0x71: 0xc4, // q  ─  horizontal line (scan line 5)
  0x72: 0xc4, // r  ⎼  scan line 7 — collapsed onto ─
  0x73: 0x5f, // s  ⎽  scan line 9 — _, the ROM's bottom-row rule
  0x74: 0xc3, // t  ├  left tee
  0x75: 0xb4, // u  ┤  right tee
  0x76: 0xc1, // v  ┴  bottom tee
  0x77: 0xc2, // w  ┬  top tee
  0x78: 0xb3, // x  │  vertical line
  0x79: 0xf3, // y  ≤  less than or equal
  0x7a: 0xf2, // z  ≥  greater than or equal
  0x7b: 0xe3, // {  π  pi
  0x7c: 0x20, // |  ≠  not equal    — no glyph in ROM
  0x7d: 0x9c, // }  £  pound sterling
  0x7e: 0xfa // ~  ·  centred dot
}

